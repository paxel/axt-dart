/// Writes `lib/src/schemas.g.dart` from the schemas of an AXT release:
/// `dart run tool/embed_schemas.dart <the release's types/axt directory>`.
///
/// The schemas are CC0-1.0 (AXT `LICENSING.md`); the library carries their
/// full JSON texts, `doc` attributes included, as the release publishes them.
library;

import 'dart:io';

void main(List<String> arguments) {
  if (arguments.length != 1) {
    stderr.writeln('usage: dart run tool/embed_schemas.dart <types/axt>');
    exitCode = 2;
    return;
  }
  final files =
      Directory(arguments.single)
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.avsc'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/embed_schemas.dart from types/axt of AXT 0.1.0.',
    )
    ..writeln(
      '// Do not edit. The schemas are CC0-1.0, as the AXT specification is.',
    )
    ..writeln()
    ..writeln('/// The JSON texts of the AXT schemas, by full name.')
    ..writeln('const Map<String, String> axtSchemaTexts = {');
  for (final file in files) {
    final text = file.readAsStringSync().trimRight();
    if (text.contains("'''")) {
      throw StateError('${file.path} holds three quotes');
    }
    final name = file.uri.pathSegments.last.replaceAll('.avsc', '');
    out
      ..writeln("  'axt.$name': r'''")
      ..writeln(text)
      ..writeln("''',");
  }
  out.writeln('};');
  File('lib/src/schemas.g.dart').writeAsStringSync(out.toString());
}
